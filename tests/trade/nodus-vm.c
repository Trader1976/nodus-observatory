/* Runs our committed bytecode with the pinned upstream test harness helpers.
 * Include path must point at nocdem/dna@2e881cc6.../shared/evm/tests.
 * This exercises the real 32-byte engine, not the JS simulation or a stock EVM.
 */
#define main nodus_library_harness_main
#include "test_contract_lib.c"
#undef main

int main(int argc, char **argv) {
    if (argc != 2) return 2;
    init_inputs();
    ctx_t c; memset(&c,0,sizeof(c));c.cfg="ObservatoryNodusSwap";
    if(load_hex(argv[1],"actual","ObservatoryNodusSwap","creation",&c.creation[0])||
       load_hex(argv[1],"actual","ObservatoryNodusSwap","runtime",&c.runtime[0]))return 2;
    evm_membackend_init(&c.mb);
    for(int i=0;i<S_COUNT;i++)add_eoa(&c.mb,ACC[i],FUND_EOA);
    if(evm_membackend_finalize(&c.mb))return 2;
    evm_membackend_bind(&c.mb,&c.be);
    c.ec.fork=EVM_FORK_PRAGUE;c.ec.addr_bytes=32;c.ec.precompile_mask=EVM_PRECOMPILES_PRAGUE;c.ec.nodus_profile=1;
    memcpy(c.ec.ticket_addr.b,TICKET,32);evm_u256_from_u64(&c.ec.ticket_unit,Q);c.ec.ticket_gas=25000;
    const char *chain="a48d1a785500a1cdecd739ecd53ef0e95b1dc4a7a300f49176a7fa25ae176114";
    uint8_t chain_bytes[32];for(int i=0;i<32;i++)chain_bytes[i]=(uint8_t)(hexval(chain[i*2])*16+hexval(chain[i*2+1]));
    evm_u256_from_be(&c.ec.chain_id,chain_bytes);c.env.number=1000;c.env.timestamp=T0;c.env.gas_limit=BLOCK_GAS;
    c.st=evm_state_new(&c.ec,&c.be);if(!c.st)return 2;
    uint8_t contract[32],secret[32],hash[32],bad[32],out[32];memset(secret,0x77,32);memset(bad,0x88,32);
    /* SHA-256 of 32 bytes 0x77, independently generated by Node crypto. */
    const char *h="e29442e61ad354e5cb0831e2e8359e8fb50cf024ad5a8f407c8f9de63bdf7371";
    for(int i=0;i<32;i++)hash[i]=(uint8_t)(hexval(h[2*i])*16+hexval(h[2*i+1]));
    if(deploy(&c,S_A,0,E0(),0,contract,NULL,"deploy address256 swap"))return 2;
    const char *open="open(bytes32,address,bytes32,uint64)",*claim="claim(address,bytes32,bytes32)",*refund="refund(bytes32)";
    const uint64_t amount=100*Q,deadline=T0+7200;
    call_rev(&c,S_A,contract,amount,open,E(U(1),B,hash,U(T0+100)),"InvalidTerms()",NULL,0,"short lock refused");
    call_rev(&c,S_A,contract,amount+1,open,E(U(1),B,hash,U(deadline)),"InvalidAmount()",NULL,0,"Nodus dust refused");
    call_ok(&c,S_A,contract,amount,open,E(U(1),B,hash,U(deadline)),NULL,"fund first leg");
    call_rev(&c,S_A,contract,amount,open,E(U(1),B,hash,U(deadline)),"SwapAlreadyExists()",NULL,0,"duplicate refused");
    call_ok(&c,S_C,contract,amount,open,E(U(1),B,hash,U(deadline)),NULL,"same id separate funder namespace");
    view_at(&c,contract,"getSwap(address,bytes32)",E(A,U(1)),0,out,"recipient address");ck_addr(&c,out,B,"all 32 recipient bytes retained");
    view_at(&c,contract,"getSwap(address,bytes32)",E(A_TWIN,U(1)),4,out,"funder twin empty");ck_u64(&c,out,0,"funder high bytes distinguish records");
    call_rev(&c,S_B_TWIN,contract,0,claim,E(A,U(1),secret),"NotRecipient()",NULL,0,"recipient twin refused");
    call_rev(&c,S_B,contract,0,claim,E(A,U(1),bad),"WrongSecret()",NULL,0,"wrong preimage refused");
    call_rev(&c,S_A,contract,0,refund,E(U(1)),"RefundNotReady()",NULL,0,"early refund refused");
    uint64_t before=bal(&c,B);
    evm_tx_result_t result;if(call_ok(&c,S_B,contract,0,claim,E(A,U(1),secret),&result,"SHA256 preimage pays recipient")){
      ck(&c,result.n_logs==1,"one claim log");if(result.n_logs==1){ck(&c,result.logs[0].data_len==64,"claim event has amount and secret");if(result.logs[0].data_len==64)ck_word(&c,result.logs[0].data+32,secret,"preimage exposed exactly");}evm_tx_result_free(&result);
    }
    ck_u64v(&c,bal(&c,B),before+amount,"exact recipient payout");
    call_rev(&c,S_B,contract,0,claim,E(A,U(1),secret),"SwapNotLocked()",NULL,0,"claim replay refused");
    at_time(&c,deadline-1);call_rev(&c,S_C,contract,0,refund,E(U(1)),"RefundNotReady()",NULL,0,"refund before boundary refused");
    at_time(&c,deadline);call_rev(&c,S_B,contract,0,claim,E(C,U(1),secret),"ClaimExpired()",NULL,0,"claim at deadline refused");
    call_ok(&c,S_C,contract,0,refund,E(U(1)),NULL,"refund at boundary");
    view(&c,contract,"lockedTotal()",E0(),out,"locked accounting");ck_u64(&c,out,0,"no locked funds left");
    post_code(&c);
    printf("Trade Nodus bytecode: %u checks passed, %u failed (32-byte Prague/Nodus profile).\n",c.pass,c.fail);
    unsigned failed=c.fail;ctx_close(&c);return failed?1:0;
}
