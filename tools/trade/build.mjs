// Reproducible dual-compiler artifacts. No keys, RPC or deployment.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import solc from 'solc';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const digest=x=>createHash('sha256').update(x).digest('hex');
const artifacts={schema:'nodus-trade/contracts-v2',upstream:'2e881cc6e6d7a5050cc10400afc2b883f8fb712a',contracts:{}};
for(const [chain,name] of [['nodus','ObservatoryNodusSwap'],['bsc','ObservatoryBscUsdtSwap'],['mockUsdt','MockUsdt']]){
  const file=name+'.sol';
  const source=fs.readFileSync(path.join(root,'contracts/trade',file),'utf8');
  const evmVersion=chain==='nodus'?'prague':'paris';
  const request={language:'Solidity',sources:{[file]:{content:source}},settings:{evmVersion,optimizer:{enabled:true,runs:200},metadata:{bytecodeHash:'none'},outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object','metadata']}}}};
  let version,result;
  if(chain==='nodus'){
    const executable=process.env.NODUS_SOLC;if(!executable)throw Error('Set NODUS_SOLC to the pinned Nodus solc binary.');
    const v=spawnSync(executable,['--version'],{encoding:'utf8'});version=v.stdout?.match(/Version: (.+)/)?.[1];
    if(v.status!==0||version!=='0.8.30+nodus.addr256.commit.73712a01.Linux.g++')throw Error('Wrong Nodus compiler.');
    const r=spawnSync(executable,['--standard-json','--no-import-callback'],{input:JSON.stringify(request),encoding:'utf8',maxBuffer:8*1024*1024});if(r.status!==0)throw Error(r.stderr);result=JSON.parse(r.stdout);
  }else{version=solc.version();if(!version.startsWith('0.8.30+commit.73712a01.'))throw Error('Wrong BNB compiler.');result=JSON.parse(solc.compile(JSON.stringify(request)));}
  if(result.errors?.length)throw Error(result.errors.map(x=>x.formattedMessage).join('\n'));
  const a=result.contracts[file][name];artifacts.contracts[chain]={name,compiler:version,evmVersion,addressBytes:chain==='nodus'?32:20,source,sourceSha256:digest(source),abi:a.abi,creation:'0x'+a.evm.bytecode.object,runtime:'0x'+a.evm.deployedBytecode.object,constructorArgs:chain==='bsc'?['address token (verified TEST-USDT deployment on chain 97)']:[]};
}
const text='/* Generated by tools/trade/build.mjs; run --check to detect drift. */\nglobalThis.NodusTradeContracts = '+JSON.stringify(artifacts,null,2)+';\n';
const out=path.join(root,'dist/trade-contracts.js');
if(process.argv.includes('--check')){if(fs.readFileSync(out,'utf8')!==text)throw Error('Contract artifacts are stale.');console.log('Trade artifacts: Nodus and BSC token compiler outputs match committed sources.');}else{fs.writeFileSync(out,text);console.log('Trade artifacts built: Nodus HTLC, BSC token HTLC and no-value TEST-USDT.');}
